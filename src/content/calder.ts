const at = (t: Record<string, [number, number][]>, k: string): [number, number] => {
  const v = t[k];
  if (!v || !v.length) {
    console.warn('calder: no position', k);
    return [1, 1];
  }
  return v[0];
};
const cp = (k: string) => at(CP, k);
const sp = (k: string) => at(SP, k);
const props = (t: Record<string, [number, number][]>, k: string, o: Omit<ObjSpawn, 'at'>): ObjSpawn[] => (t[k] ?? []).map((p) => ({ ...o, at: p }));

