const MARKET_IDS = ['cr_mh0', 'cr_mh1', 'cr_mh2', 'cr_mh3', 'cr_mh4'];

function tamsinTrusts(c: Ctx) {
  return !!(c.flag('cr_pumpFixed') || c.flag('cr_marketCleared') || c.flag('cr_keyGiven'));
}

function giveMaintKey(c: Ctx) {
  if (c.flag('cr_keyGiven')) return;
  c.set('cr_keyGiven');
  c.give('cr_maintKey');
  c.quest('cr_door', 'Tamsin Hale gave me the Transit Authority service key. The shed north-west of the concourse hides a shaft down into Shelter 7.');
}

function openGreatDoor(c: Ctx) {
  c.set('cr_greatDoorOpen');
  const o = c.obj('cr_greatDoor');
  if (o) {
    o.locked = 0;
    o.open = true;
    if (G.map) G.map.version++;
  }
  c.sound('hatch');
}

function bless(c: Ctx, how: string) {
  if (c.flag('cr_sealedBlessing')) return;
  c.set('cr_sealedBlessing', how);
  openGreatDoor(c);
  c.quest('cr_door', 'Prior Dunne of the Sealed opened the Door of Shelter 7 for me.');
  c.xp(200);
}

function livingNear(team: string, radius: number) {
  const m = G.map;
  if (!m) return [];
  const p = G.state.player;
  return m.actors.filter((a) => a.team === team && !a.dead && hexDist(a, p) <= radius);
}

function marketCleared(c: Ctx) {
  return MARKET_IDS.every((id) => c.flag('dead:' + id));
}

function flushRads(amount: number) {
  const p = G.state.player;
  p.rads = Math.max(0, p.rads - amount);
  syncRadEffect(p);
}

